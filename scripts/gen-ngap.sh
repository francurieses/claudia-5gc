#!/usr/bin/env bash
# Regenerates shared/ngap/ngapType from the extracted TS 38.413 ASN.1 (go:generate hook).
# specs/asn1/ is git-ignored (3GPP text is not committed; regenerate with scripts/extract-asn1.sh),
# so when it is absent (e.g. CI) this is a no-op and the committed generated Go is authoritative.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
ver="${NGAP_ASN1_VERSION:-V19.4.0}"
in="$root/specs/asn1/ngap/r19"
if ! ls "$in"/*.asn >/dev/null 2>&1; then
  echo "gen-ngap: $in missing; keeping committed shared/ngap/ngapType (run scripts/extract-asn1.sh to regenerate)" >&2
  exit 0
fi
cd "$root"
GOWORK=off go run ./tools/asn1gen -in "$in" -out shared/ngap/ngapType -pkg ngapType \
  -header "Code generated by tools/asn1gen from TS 38.413 $ver. DO NOT EDIT."
