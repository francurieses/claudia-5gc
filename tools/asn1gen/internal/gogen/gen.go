// Package gogen turns parsed NGAP ASN.1 modules (package asn1) into Go types with
// github.com/free5gc/aper struct tags, following the shapes of free5gc/ngap ngapType:
// the same type, field and constant names and the same tag vocabulary.
//
// Rules (derived from the ASN.1 and checked against free5gc/ngap v1.1.3 by the golden
// test in tools/asn1gen):
//
//   - a primitive type assignment becomes struct{ Value T } carrying the PER constraints;
//   - SEQUENCE becomes a struct, OPTIONAL components pointers tagged "optional";
//   - SEQUENCE OF becomes struct{ List []Elem };
//   - CHOICE becomes struct{ Present int; Alt *T ... } plus <Type>Present<Alt> constants;
//   - ENUMERATED becomes struct{ Value aper.Enumerated } plus <Type>Present<Item> constants;
//   - parameterised containers (ProtocolIE-Container, ProtocolExtensionContainer,
//     ProtocolIE-SingleContainer, PrivateIE-Container) are instantiated per object set,
//     and the open-type value of each field is a struct with one pointer per object.
package gogen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"github.com/francurieses/claudia-5gc/tools/asn1gen/internal/asn1"
)

// Config controls code generation.
type Config struct {
	// Package is the Go package name of the output.
	Package string
	// Header is the text of the first comment line, e.g.
	// "Code generated by tools/asn1gen from TS 38.413 V19.4.0. DO NOT EDIT."
	Header string
	// AperImport is the import path of the aper library.
	AperImport string
}

type typeDef struct {
	ta  *asn1.TypeAssign
	mod *asn1.Module
}

type gen struct {
	cfg     Config
	mods    []*asn1.Module
	types   map[string]*typeDef
	params  map[string]*typeDef
	values  map[string]asn1.Value
	classes map[string]*asn1.Class
	// classOwner and objectOwner record the defining module to reject cross-module duplicates.
	classOwner, objectOwner map[string]string
	objects                 map[string]*asn1.Object

	bufs     map[string]*bytes.Buffer
	declared map[string]string // Go identifier -> origin (for duplicate detection)
	usedNull bool
	derived  string // file receiving instantiated containers and field structs
}

// Generate returns file name -> gofmt'ed Go source for the given modules. Output is
// deterministic: modules are processed in the given order, assignments in source order.
func Generate(mods []*asn1.Module, cfg Config) (map[string][]byte, error) {
	if cfg.Package == "" || cfg.AperImport == "" {
		return nil, fmt.Errorf("gogen: Config.Package and Config.AperImport are required")
	}
	g := &gen{
		cfg: cfg, mods: mods,
		types: map[string]*typeDef{}, params: map[string]*typeDef{},
		values: map[string]asn1.Value{}, classes: map[string]*asn1.Class{},
		classOwner: map[string]string{}, objectOwner: map[string]string{},
		objects: map[string]*asn1.Object{}, bufs: map[string]*bytes.Buffer{},
		declared: map[string]string{}, derived: "protocol_containers.go",
	}
	if err := g.index(); err != nil {
		return nil, err
	}
	for _, m := range mods {
		file := fileName(m.Name)
		g.buf(file) // create even when empty
		for _, r := range m.Order {
			var err error
			switch r.Kind {
			case asn1.RefType:
				ta := m.Types[r.Name]
				if len(ta.Params) > 0 {
					continue
				}
				err = g.emitType(file, m, ta)
			case asn1.RefValue:
				err = g.emitID(file, m.Values[r.Name])
			}
			if err != nil {
				return nil, err
			}
		}
	}
	if g.usedNull {
		g.printf(g.derived, "// Null is the Go form of the ASN.1 NULL type: a SEQUENCE without components\n// encodes to zero bits in PER, which is exactly NULL.\ntype Null struct{}\n\n")
	}
	out := map[string][]byte{}
	names := make([]string, 0, len(g.bufs))
	for n, b := range g.bufs {
		if b.Len() > 0 {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	for _, n := range names {
		body := g.bufs[n].String()
		var src bytes.Buffer
		fmt.Fprintf(&src, "// %s\n\npackage %s\n\n", cfg.Header, cfg.Package)
		if strings.Contains(body, "aper.") {
			fmt.Fprintf(&src, "import %q\n\n", cfg.AperImport)
		}
		src.WriteString(body)
		fmtd, err := format.Source(src.Bytes())
		if err != nil {
			return nil, fmt.Errorf("gogen: gofmt %s: %w", n, err)
		}
		out[n] = fmtd
	}
	return out, nil
}

func fileName(module string) string {
	return strings.ToLower(strings.ReplaceAll(module, "-", "_")) + ".go"
}

func (g *gen) buf(file string) *bytes.Buffer {
	b := g.bufs[file]
	if b == nil {
		b = &bytes.Buffer{}
		g.bufs[file] = b
	}
	return b
}

func (g *gen) printf(file, format string, args ...any) {
	fmt.Fprintf(g.buf(file), format, args...)
}

// declare records a Go identifier and fails on a duplicate.
func (g *gen) declare(name, origin string) error {
	if prev, ok := g.declared[name]; ok {
		return fmt.Errorf("gogen: Go identifier %s from %s already declared by %s", name, origin, prev)
	}
	g.declared[name] = origin
	return nil
}

// index builds the global namespace. NGAP names are unique across its six modules.
func (g *gen) index() error {
	for _, m := range g.mods {
		for n, ta := range m.Types {
			dst := g.types
			if len(ta.Params) > 0 {
				dst = g.params
			}
			if prev, dup := dst[n]; dup {
				return fmt.Errorf("gogen: type %s defined in both %s and %s", n, prev.mod.Name, m.Name)
			}
			dst[n] = &typeDef{ta, m}
		}
		for n, v := range m.Values {
			if prev, dup := g.values[n]; dup && prev != v.Value {
				return fmt.Errorf("gogen: value %s defined twice with different values", n)
			}
			g.values[n] = v.Value
		}
		for n, c := range m.Classes {
			if prev, dup := g.classOwner[n]; dup {
				return fmt.Errorf("gogen: class %s defined in both %s and %s", n, prev, m.Name)
			}
			g.classOwner[n] = m.Name
			g.classes[n] = c
		}
		for n, o := range m.Objects {
			if prev, dup := g.objectOwner[n]; dup {
				return fmt.Errorf("gogen: object set %s defined in both %s and %s", n, prev, m.Name)
			}
			g.objectOwner[n] = m.Name
			g.objects[n] = o
		}
	}
	return nil
}

// valueNum resolves a value (literal or constant reference) to its decimal text.
func (g *gen) valueNum(v asn1.Value, subst map[string]asn1.Value) (string, error) {
	for depth := 0; depth < 8; depth++ {
		if v.IsNum {
			return strconv.FormatInt(v.Num, 10), nil
		}
		if s, ok := subst[v.Name]; ok {
			v = s
			continue
		}
		c, ok := g.values[v.Name]
		if !ok {
			return "", fmt.Errorf("gogen: undefined value %q", v.Name)
		}
		v = c
	}
	return "", fmt.Errorf("gogen: value %q: reference loop", v.Name)
}

func (g *gen) bound(b asn1.Bound, subst map[string]asn1.Value) (string, error) {
	switch b.Kind {
	case asn1.BoundNum:
		return b.Lit, nil
	case asn1.BoundName:
		return g.valueNum(asn1.Value{Name: b.Name}, subst)
	}
	return "", nil // MIN / MAX: unbounded on that side
}

func (g *gen) rangeBounds(r *asn1.Range, subst map[string]asn1.Value) (lo, hi string, err error) {
	if lo, err = g.bound(r.Lo, subst); err != nil {
		return "", "", err
	}
	if hi, err = g.bound(r.Hi, subst); err != nil {
		return "", "", err
	}
	return lo, hi, nil
}

// terminal follows plain alias chains (A ::= B) to the defining type.
func (g *gen) terminal(name string) (*asn1.Type, error) {
	for depth := 0; depth < 16; depth++ {
		td, ok := g.types[name]
		if !ok {
			if _, isParam := g.params[name]; isParam {
				return nil, fmt.Errorf("gogen: parameterised type %s used without actual parameters", name)
			}
			return nil, fmt.Errorf("gogen: undefined type %q", name)
		}
		t := td.ta.Type
		if t.Kind == asn1.KindRef && len(t.Args) == 0 {
			name = t.Ref
			continue
		}
		return t, nil
	}
	return nil, fmt.Errorf("gogen: type alias loop at %q", name)
}

// refTags are the field-site tags free5gc puts on a component whose type is the named
// type: valueExt for an extensible SEQUENCE, valueLB:0,valueUB:n-1 (plus valueExt when
// extensible) for a CHOICE with n root alternatives; every other type carries its
// constraints inside its own Value struct.
func (g *gen) refTags(name string) (tagSet, error) {
	t, err := g.terminal(name)
	if err != nil {
		return tagSet{}, err
	}
	var ts tagSet
	switch t.Kind {
	case asn1.KindSequence:
		ts.valueExt = t.Extensible
	case asn1.KindChoice:
		ts.valueExt = t.Extensible
		ts.vlb, ts.vub = "0", strconv.Itoa(rootCount(t.Components)-1)
	}
	return ts, nil
}

func rootCount(cs []asn1.Component) int {
	n := 0
	for _, c := range cs {
		if !c.ExtAddition {
			n++
		}
	}
	return n
}

// goType returns the Go type text and tags for a component type. Named types carry no
// tags of their own beyond refTags; built-in types carry their PER constraints.
func (g *gen) goType(file string, t *asn1.Type, subst map[string]asn1.Value, origin string) (string, tagSet, error) {
	var ts tagSet
	if err := checkConstraint(t, origin); err != nil {
		return "", ts, err
	}
	switch t.Kind {
	case asn1.KindRef:
		if len(t.Args) > 0 {
			name, err := g.instantiate(t.Ref, t.Args, "", subst, origin)
			return name, ts, err
		}
		ts, err := g.refTags(t.Ref)
		return goName(t.Ref), ts, err
	case asn1.KindInteger:
		if r := t.Constraint.Value; r != nil {
			lo, hi, err := g.rangeBounds(r, subst)
			if err != nil {
				return "", ts, err
			}
			ts.valueExt, ts.vlb, ts.vub = r.Ext, lo, hi
		}
		return "int64", ts, nil
	case asn1.KindBitString, asn1.KindOctetString, asn1.KindCharString:
		if t.Kind == asn1.KindCharString && t.CharString == "NumericString" {
			return "", ts, fmt.Errorf("gogen: %s: line %d: NumericString (4-bit characters) is not supported", origin, t.Line)
		}
		// A SIZE constraint on UTF8String is not PER-visible (X.691 clause 30.5.3 lists the
		// known-multiplier string types only), so it must not become a size tag.
		if r := t.Constraint.Size; r != nil && t.CharString != "UTF8String" {
			lo, hi, err := g.rangeBounds(r, subst)
			if err != nil {
				return "", ts, err
			}
			ts.sizeExt, ts.slb, ts.sub = r.Ext, lo, hi
		}
		switch {
		case t.Kind == asn1.KindBitString:
			return "aper.BitString", ts, nil
		case t.Kind == asn1.KindCharString && t.CharString == "PrintableString":
			return "string", ts, nil
		}
		// OCTET STRING, and the character strings whose aligned-PER encoding is a plain octet
		// string (VisibleString and IA5String use 8-bit characters; UTF8String is an
		// unconstrained octet string, X.691 clauses 30.5.7 and 30.5.8). aper's `string` path
		// validates the PrintableString alphabet, which would reject valid VisibleString and
		// UTF8String values, so these map to aper.OctetString.
		return "aper.OctetString", ts, nil
	case asn1.KindEnumerated:
		// Inline ENUMERATED: like free5gc, a bare aper.Enumerated with the PER range and no
		// symbolic constants.
		var root int64
		for _, e := range t.Enums {
			if !e.ExtAddition {
				root++
			}
		}
		ts.valueExt, ts.vlb, ts.vub = t.Extensible, "0", strconv.FormatInt(root-1, 10)
		return "aper.Enumerated", ts, nil
	case asn1.KindOID:
		return "aper.ObjectIdentifier", ts, nil
	case asn1.KindNull:
		g.usedNull = true
		return "Null", ts, nil
	case asn1.KindBoolean:
		return "bool", ts, nil
	}
	return "", ts, fmt.Errorf("gogen: %s: line %d: inline %s types are not supported (name the type)", origin, t.Line, kindName(t.Kind))
}

// checkConstraint rejects constraints the generator parsed but would otherwise drop
// silently: CONTAINING anywhere, and value/SIZE/table constraints on a type reference or
// class-field component (a constrained reference needs a derived type, which is unsupported).
func checkConstraint(t *asn1.Type, origin string) error {
	c := t.Constraint
	// OCTET STRING (CONTAINING T) encodes as a plain octet string in aligned PER (X.691
	// clause 30.5.x; the contents are an opaque encoding of T, as in free5gc/ngap), so it is
	// handled by the octet-string path. Anywhere else it is unsupported.
	if c.Containing != "" && (t.Kind != asn1.KindOctetString || c.Size != nil) {
		return fmt.Errorf("gogen: %s: line %d: CONTAINING is only supported on an unsized OCTET STRING", origin, t.Line)
	}
	switch t.Kind {
	case asn1.KindRef:
		if c.Value != nil || c.Size != nil || len(c.ObjectSets) > 0 {
			return fmt.Errorf("gogen: %s: line %d: constraint on type reference %s is not supported", origin, t.Line, t.Ref)
		}
	case asn1.KindClassField:
		if c.Value != nil || c.Size != nil {
			return fmt.Errorf("gogen: %s: line %d: value/SIZE constraint on a class-field type is not supported", origin, t.Line)
		}
	}
	return nil
}

func kindName(k asn1.Kind) string {
	switch k {
	case asn1.KindSequence:
		return "SEQUENCE"
	case asn1.KindSequenceOf:
		return "SEQUENCE OF"
	case asn1.KindChoice:
		return "CHOICE"
	case asn1.KindEnumerated:
		return "ENUMERATED"
	case asn1.KindClassField:
		return "class-field"
	}
	return "unknown"
}

// doc is the doc comment line of the Go type generated for a type assignment.
func doc(m *asn1.Module, ta *asn1.TypeAssign) string {
	return fmt.Sprintf("// %s is the ASN.1 type %s of module %s.\n", goName(ta.Name), ta.Name, m.Name)
}

// emitID emits "id-X Type ::= n" as the constant <Type><X> when Type is an INTEGER type
// (ProtocolIE-ID -> ProtocolIEIDX, ProcedureCode -> ProcedureCodeX). Other value
// assignments (maxnoofX limits) are only consumed as constraint bounds.
func (g *gen) emitID(file string, v *asn1.ValueAssign) error {
	if !strings.HasPrefix(v.Name, "id-") {
		return nil
	}
	t, err := g.terminal(v.Type)
	if err != nil || t.Kind != asn1.KindInteger {
		return fmt.Errorf("gogen: value %s: type %s is not an INTEGER type", v.Name, v.Type)
	}
	n, err := g.valueNum(v.Value, nil)
	if err != nil {
		return err
	}
	name := goName(v.Type) + goName(idName(v.Name))
	if err := g.declare(name, "value "+v.Name); err != nil {
		return err
	}
	g.printf(file, "// %s is %s ::= %s.\nconst %s int64 = %s\n\n", name, v.Name, n, name, n)
	return nil
}

func (g *gen) emitType(file string, m *asn1.Module, ta *asn1.TypeAssign) error {
	name := goName(ta.Name)
	origin := m.Name + "." + ta.Name
	if err := g.declare(name, origin); err != nil {
		return err
	}
	t := ta.Type
	if err := checkConstraint(t, origin); err != nil {
		return err
	}
	switch t.Kind {
	case asn1.KindSequence:
		return g.emitSequence(file, doc(m, ta), name, t, nil, origin)
	case asn1.KindChoice:
		return g.emitChoice(file, doc(m, ta), name, t, origin)
	case asn1.KindEnumerated:
		return g.emitEnum(file, doc(m, ta), name, t, origin)
	case asn1.KindSequenceOf:
		return g.emitSequenceOf(file, doc(m, ta), name, t, nil, origin)
	case asn1.KindRef:
		if len(t.Args) > 0 {
			return fmt.Errorf("gogen: %s: type assignment from an instantiated parameterised type is not supported", origin)
		}
		if _, err := g.terminal(t.Ref); err != nil {
			return fmt.Errorf("gogen: %s: %w", origin, err)
		}
		g.printf(file, "%stype %s = %s\n\n", doc(m, ta), name, goName(t.Ref))
		return nil
	}
	gt, ts, err := g.goType(file, t, nil, origin)
	if err != nil {
		return err
	}
	g.printf(file, "%stype %s struct {\n\tValue %s%s\n}\n\n", doc(m, ta), name, gt, ts.tag())
	return nil
}

func (g *gen) emitEnum(file, doc, name string, t *asn1.Type, origin string) error {
	var root, next int64
	for _, e := range t.Enums {
		if !e.ExtAddition {
			root++
		}
	}
	if root == 0 {
		return fmt.Errorf("gogen: %s: empty ENUMERATED", origin)
	}
	for _, e := range t.Enums {
		if e.Value >= 0 {
			// PER encodes the rank of the enumerator, not its number; aper takes the number as
			// the rank, so explicit numbers would silently mis-encode.
			return fmt.Errorf("gogen: %s: enumerator %s has an explicit number, not supported", origin, e.Name)
		}
	}
	g.printf(file, "const (\n")
	seen := map[int64]bool{}
	for _, e := range t.Enums {
		v := next
		if e.Value >= 0 {
			v = e.Value
		}
		if seen[v] {
			return fmt.Errorf("gogen: %s: enumerator %s repeats value %d", origin, e.Name, v)
		}
		seen[v] = true
		next = v + 1
		cn := name + "Present" + goName(e.Name)
		if err := g.declare(cn, origin); err != nil {
			return err
		}
		g.printf(file, "\t%s aper.Enumerated = %d\n", cn, v)
	}
	g.printf(file, ")\n\n")
	ts := tagSet{valueExt: t.Extensible, vlb: "0", vub: strconv.FormatInt(root-1, 10)}
	g.printf(file, "%stype %s struct {\n\tValue aper.Enumerated%s\n}\n\n", doc, name, ts.tag())
	return nil
}

func (g *gen) emitSequenceOf(file, doc, name string, t *asn1.Type, subst map[string]asn1.Value, origin string) error {
	et, ts, err := g.goType(file, t.Elem, subst, origin)
	if err != nil {
		return err
	}
	if r := t.Constraint.Size; r != nil {
		lo, hi, err := g.rangeBounds(r, subst)
		if err != nil {
			return err
		}
		ts.sizeExt, ts.slb, ts.sub = r.Ext, lo, hi
	}
	g.printf(file, "%stype %s struct {\n\tList []%s%s\n}\n\n", doc, name, et, ts.tag())
	return nil
}

func (g *gen) emitChoice(file, doc, name string, t *asn1.Type, origin string) error {
	if len(t.Components) == 0 {
		return fmt.Errorf("gogen: %s: empty CHOICE", origin)
	}
	if err := g.declare(name+"PresentNothing", origin); err != nil {
		return err
	}
	var consts, fields strings.Builder
	fmt.Fprintf(&consts, "const (\n\t%sPresentNothing int = iota /* No components present */\n", name)
	fmt.Fprintf(&fields, "%stype %s struct {\n\tPresent int\n", doc, name)
	for _, c := range t.Components {
		if c.ExtAddition {
			return fmt.Errorf("gogen: %s: CHOICE extension additions (%s) are not supported", origin, c.Name)
		}
		fn := goName(c.Name)
		cn := name + "Present" + fn
		if err := g.declare(cn, origin); err != nil {
			return err
		}
		gt, ts, err := g.goType(file, c.Type, nil, origin+"."+c.Name)
		if err != nil {
			return err
		}
		fmt.Fprintf(&consts, "\t%s\n", cn)
		fmt.Fprintf(&fields, "\t%s *%s%s\n", fn, gt, ts.tag())
	}
	if t.Extensible {
		consts.WriteString("\t/* Extensions may appear below */\n")
	}
	consts.WriteString(")\n\n")
	fields.WriteString("}\n\n")
	g.printf(file, "%s%s", consts.String(), fields.String())
	return nil
}

// emitSequence emits a SEQUENCE struct. Components typed CLASS.&field are the
// information-object-class projections of X.681: a fixed-type value field becomes the
// field's governing type, a type field (&Value) becomes an open type whose Go struct
// <Struct><Field> has one pointer per object of the constraining object set.
func (g *gen) emitSequence(file, doc, name string, t *asn1.Type, subst map[string]asn1.Value, origin string) error {
	var fields strings.Builder
	fmt.Fprintf(&fields, "%stype %s struct {\n", doc, name)
	seen := map[string]bool{}
	refName := ""
	for i, c := range t.Components {
		if c.ExtAddition {
			return fmt.Errorf("gogen: %s: SEQUENCE extension additions (%s) are not supported", origin, c.Name)
		}
		fn := goName(c.Name)
		if seen[fn] {
			return fmt.Errorf("gogen: %s: duplicate field name %s", origin, fn)
		}
		seen[fn] = true
		if i == 0 {
			refName = fn
		}
		var gt string
		var ts tagSet
		if c.Type.Kind == asn1.KindClassField {
			if c.Optional || c.Default != nil {
				return fmt.Errorf("gogen: %s.%s: OPTIONAL/DEFAULT on a class-field component is not supported", origin, c.Name)
			}
			if err := checkConstraint(c.Type, origin+"."+c.Name); err != nil {
				return err
			}
			cls, ok := g.classes[c.Type.ClassName]
			if !ok {
				return fmt.Errorf("gogen: %s: unknown class %s", origin, c.Type.ClassName)
			}
			cf := findClassField(cls, c.Type.ClassField)
			if cf == nil {
				return fmt.Errorf("gogen: %s: class %s has no field &%s", origin, cls.Name, c.Type.ClassField)
			}
			if !cf.IsType {
				gt = goName(cf.Type)
			} else {
				if len(c.Type.Constraint.ObjectSets) == 0 {
					return fmt.Errorf("gogen: %s.%s: open type without an object set constraint", origin, c.Name)
				}
				set := c.Type.Constraint.ObjectSets[0]
				if s, ok := subst[set]; ok {
					set = s.Name
				}
				gt = name + fn
				ts = tagSet{openType: true, refName: refName}
				if err := g.emitOpenValue(file, name, gt, cls, cf, set, origin); err != nil {
					return err
				}
			}
		} else {
			var err error
			if gt, ts, err = g.goType(file, c.Type, subst, origin+"."+c.Name); err != nil {
				return err
			}
			switch {
			case c.Optional:
				gt, ts.optional = "*"+gt, true
			case c.Default != nil:
				d, err := g.valueNum(*c.Default, subst)
				if err != nil {
					return fmt.Errorf("gogen: %s.%s: only integer DEFAULT values are supported: %w", origin, c.Name, err)
				}
				ts.defaultValue = d
			}
		}
		fmt.Fprintf(&fields, "\t%s %s%s\n", fn, gt, ts.tag())
	}
	fields.WriteString("}\n\n")
	g.printf(file, "%s", fields.String())
	return nil
}

func findClassField(c *asn1.Class, name string) *asn1.ClassField {
	for i := range c.Fields {
		if c.Fields[i].Name == name {
			return &c.Fields[i]
		}
	}
	return nil
}

// member is one object of an object set, keyed by class field name.
type member struct {
	id    *asn1.Value              // value of the class's UNIQUE field
	types map[string]*asn1.Type    // type-field values by class field name
	vals  map[string]*asn1.Value   // value-field values by class field name
	raw   map[string]asn1.ObjField // keyed by class field name
}

// flatten expands an object set (following references to other sets and objects) into
// its members in source order.
func (g *gen) flatten(set string, cls *asn1.Class, depth int) ([]member, error) {
	if depth > 16 {
		return nil, fmt.Errorf("gogen: object set %s: reference loop", set)
	}
	o, ok := g.objects[set]
	if !ok {
		return nil, fmt.Errorf("gogen: undefined object set %q", set)
	}
	if !o.IsSet {
		m, err := g.makeMember(o.Fields, cls, set)
		if err != nil {
			return nil, err
		}
		return []member{m}, nil
	}
	var out []member
	for _, e := range o.Elems {
		switch {
		case e.Ellipsis:
		case e.Ref != "":
			sub, err := g.flatten(e.Ref, cls, depth+1)
			if err != nil {
				return nil, err
			}
			out = append(out, sub...)
		default:
			m, err := g.makeMember(e.Inline, cls, fmt.Sprintf("%s (line %d)", set, e.InlineLn))
			if err != nil {
				return nil, err
			}
			out = append(out, m)
		}
	}
	return out, nil
}

func (g *gen) makeMember(fields map[string]asn1.ObjField, cls *asn1.Class, where string) (member, error) {
	m := member{types: map[string]*asn1.Type{}, vals: map[string]*asn1.Value{}, raw: map[string]asn1.ObjField{}}
	for phrase, f := range fields {
		fname, ok := cls.Syntax[phrase]
		if !ok {
			return m, fmt.Errorf("gogen: object %s: keyword %q is not in WITH SYNTAX of class %s", where, phrase, cls.Name)
		}
		m.raw[fname] = f
		if f.Type != nil {
			m.types[fname] = f.Type
		} else {
			m.vals[fname] = f.Value
		}
	}
	for _, cf := range cls.Fields {
		if cf.Unique {
			v := m.vals[cf.Name]
			if v == nil {
				return m, fmt.Errorf("gogen: object %s: missing UNIQUE field &%s", where, cf.Name)
			}
			m.id = v
		}
	}
	return m, nil
}

// emitOpenValue emits the <owner>Present constants and the open-type value struct for
// type field cf of cls over the members of object set `set`.
func (g *gen) emitOpenValue(file, owner, valueStruct string, cls *asn1.Class, cf *asn1.ClassField, set, origin string) error {
	members, err := g.flatten(set, cls, 0)
	if err != nil {
		return fmt.Errorf("gogen: %s: %w", origin, err)
	}
	typeFields := 0
	for _, f := range cls.Fields {
		if f.IsType {
			typeFields++
		}
	}
	if err := g.declare(valueStruct, origin); err != nil {
		return err
	}
	if err := g.declare(owner+"PresentNothing", origin); err != nil {
		return err
	}
	var consts, fields strings.Builder
	fmt.Fprintf(&consts, "const (\n\t%sPresentNothing int = iota /* No components present */\n", owner)
	fmt.Fprintf(&fields, "type %s struct {\n\tPresent int\n", valueStruct)
	seen := map[string]bool{}
	for _, mb := range members {
		t := mb.types[cf.Name]
		if t == nil {
			continue // object without this (OPTIONAL) type field
		}
		var fn string
		if typeFields == 1 {
			// IE classes: the member is named after its identifier (id-X -> X).
			if mb.id == nil || mb.id.IsNum {
				return fmt.Errorf("gogen: %s: object set %s: member without a symbolic id", origin, set)
			}
			fn = goName(idName(mb.id.Name))
		} else {
			// Procedure classes: the member is named after the message type.
			if t.Kind != asn1.KindRef {
				return fmt.Errorf("gogen: %s: object set %s: member type must be a named type", origin, set)
			}
			fn = goName(t.Ref)
		}
		if seen[fn] {
			return fmt.Errorf("gogen: %s: object set %s: duplicate member %s", origin, set, fn)
		}
		seen[fn] = true
		idNum, err := g.valueNum(*mb.id, nil)
		if err != nil {
			return fmt.Errorf("gogen: %s: %w", origin, err)
		}
		gt, ts, err := g.goType(file, t, nil, origin+"."+fn)
		if err != nil {
			return err
		}
		ts.refValue = idNum
		cn := owner + "Present" + fn
		if err := g.declare(cn, origin); err != nil {
			return err
		}
		fmt.Fprintf(&consts, "\t%s\n", cn)
		fmt.Fprintf(&fields, "\t%s *%s%s\n", fn, gt, ts.tag())
	}
	consts.WriteString(")\n\n")
	fields.WriteString("}\n\n")
	g.printf(file, "%s%s", consts.String(), fields.String())
	return nil
}

// instantiate emits (once) the Go types for an instantiation of a parameterised type
// and returns the Go name of the top-level one. hint is the struct name to use when the
// definition is a SEQUENCE with class-field components (ProtocolIE-Field et al.).
func (g *gen) instantiate(def string, args []asn1.Arg, hint string, outer map[string]asn1.Value, origin string) (string, error) {
	pd, ok := g.params[def]
	if !ok {
		return "", fmt.Errorf("gogen: %s: unknown parameterised type %s", origin, def)
	}
	ta := pd.ta
	if len(args) != len(ta.Params) {
		return "", fmt.Errorf("gogen: %s: %s expects %d parameters, got %d", origin, def, len(ta.Params), len(args))
	}
	subst := map[string]asn1.Value{}
	set := ""
	for i, p := range ta.Params {
		a := args[i]
		switch {
		case a.ObjectSet != "":
			s := a.ObjectSet
			if o, ok := outer[s]; ok { // actual parameter that is itself a formal parameter
				s = o.Name
			}
			if set != "" {
				return "", fmt.Errorf("gogen: %s: %s: more than one object-set parameter is not supported", origin, def)
			}
			set = s
			subst[p.Name] = asn1.Value{Name: s}
		case a.Value != nil:
			if !a.Value.IsNum {
				if o, ok := outer[a.Value.Name]; ok {
					subst[p.Name] = o
					continue
				}
			}
			subst[p.Name] = *a.Value
		}
	}
	if set == "" {
		return "", fmt.Errorf("gogen: %s: %s: no object-set parameter", origin, def)
	}
	if len(subst) != 1 {
		return "", fmt.Errorf("gogen: %s: %s: value parameters (bounds) are not supported", origin, def)
	}
	body := ta.Type
	switch body.Kind {
	case asn1.KindSequenceOf:
		name := goName(def) + goName(set)
		if _, done := g.declared[name]; done {
			return name, nil
		}
		if err := g.declare(name, origin); err != nil {
			return "", err
		}
		if body.Elem.Kind != asn1.KindRef {
			return "", fmt.Errorf("gogen: %s: element of %s must be a type reference", origin, def)
		}
		// emitSequenceOf instantiates the element through goType (hint: the set name).
		return name, g.emitSequenceOf(g.derived, "", name, body, subst, origin)
	case asn1.KindRef:
		name := goName(def) + goName(set)
		if _, done := g.declared[name]; done {
			return name, nil
		}
		if _, err := g.instantiate(body.Ref, body.Args, name, subst, origin); err != nil {
			return "", err
		}
		return name, nil
	case asn1.KindSequence:
		if hint == "" {
			hint = goName(set)
		}
		if _, done := g.declared[hint]; done {
			return hint, nil
		}
		if err := g.declare(hint, origin); err != nil {
			return "", err
		}
		return hint, g.emitSequence(g.derived, "", hint, body, subst, origin)
	}
	return "", fmt.Errorf("gogen: %s: unsupported body of parameterised type %s", origin, def)
}
