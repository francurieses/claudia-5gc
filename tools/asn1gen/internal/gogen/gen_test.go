var cfg = Config{Package: "p", Header: "Code generated by tools/asn1gen test. DO NOT EDIT.", AperImport: "github.com/free5gc/aper"}

var spaces = regexp.MustCompile(`\s+`)

func norm(s string) string { return spaces.ReplaceAllString(s, " ") }

// gen parses the synthetic base module plus a snippet module and returns the concatenated output.
func generate(t *testing.T, snippet string) (string, error) {
	t.Helper()
	base, err := os.ReadFile("../../testdata/synthetic/SYN-Base.asn")
	if err != nil {
		t.Fatal(err)
	}
	mb, err := asn1.ParseModule("SYN-Base.asn", string(base))
	if err != nil {
		t.Fatal(err)
	}
	ms, err := asn1.ParseModule("snippet.asn", "S DEFINITIONS AUTOMATIC TAGS ::= BEGIN\n"+snippet+"\nEND")
	if err != nil {
		t.Fatalf("snippet: %v", err)
	}
	files, err := Generate([]*asn1.Module{mb, ms}, cfg)
	if err != nil {
		return "", err
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	var all strings.Builder
	for _, n := range names {
		all.Write(files[n])
	}
	return norm(all.String()), nil
}

