func TestGenerateErrors(t *testing.T) {
	tests := []struct {
		name, asn, want string
	}{
		{"explicit enumerator number", "E ::= ENUMERATED { a, b(5) }", "explicit number"},
		{"inline sequence", "S ::= SEQUENCE { a SEQUENCE { b INTEGER } }", "inline SEQUENCE"},
		{"inline choice", "S ::= SEQUENCE { a CHOICE { b INTEGER } }", "inline CHOICE"},
		{"undefined type", "S ::= SEQUENCE { a Nope }", "undefined type"},
		{"undefined bound", "S ::= INTEGER (0..maxNope)", "undefined value"},
		{"duplicate go name", "A-B ::= INTEGER\nAB ::= INTEGER", "already declared"},
		{"choice with Nothing alternative", "C ::= CHOICE { nothing INTEGER, b INTEGER }", "already declared"},
		{"extension additions", "S ::= SEQUENCE { a INTEGER, ..., b INTEGER }", "extension additions"},
		{"numeric string", "S ::= NumericString", "NumericString"},
		{"constraint on type reference", "A ::= INTEGER (0..3)\nS ::= SEQUENCE { a A (SIZE(1..2)) }", "constraint on type reference"},
		{"containing on non-octet", "S ::= BIT STRING (CONTAINING A)\nA ::= INTEGER", "CONTAINING is only supported"},
		{"class field optional", "S ::= SEQUENCE { id SYN-IES.&id OPTIONAL }", "OPTIONAL/DEFAULT on a class-field"},
		{"duplicate class across modules", "SYN-IES ::= CLASS { &id INTEGER UNIQUE }", "class SYN-IES defined in both"},
		{"unknown container set", "M ::= SEQUENCE { p ProtocolIE-Container { {Nope} } }", "undefined object set"},
		{"unknown parameterised", "M ::= SEQUENCE { p Nope { {X} } }", "unknown parameterised type"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			_, err := generate(t, tc.asn)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("error = %v, want containing %q", err, tc.want)
			}
		})
	}
}

func TestGenerateDeterministicAndHeader(t *testing.T) {
	const src = "A ::= INTEGER (0..3)\nB ::= SEQUENCE { a A }"
	first, err := generate(t, src)
	if err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 5; i++ {
		again, err := generate(t, src)
		if err != nil || again != first {
			t.Fatalf("run %d differs (err=%v)", i, err)
		}
	}
	if !strings.HasPrefix(first, "// Code generated by tools/asn1gen test. DO NOT EDIT. package p") {
		t.Errorf("header missing: %.80s", first)
	}
}

func TestGoName(t *testing.T) {
	for in, want := range map[string]string{
		"iE-Extensions": "IEExtensions", "S-NSSAI": "SNSSAI", "gBR-QosInformation": "GBRQosInformation",
		"release-due-to-5gc-generated-reason": "ReleaseDueTo5gcGeneratedReason", "uEAggregateMaximumBitRateDL": "UEAggregateMaximumBitRateDL",
		"id-AMFName": "IdAMFName", "a": "A",
	} {
		if got := goName(in); got != want {
			t.Errorf("goName(%q) = %q, want %q", in, got, want)
		}
	}
}

