// TestGenerateContainingAndUint64 pins the explicit behaviours: OCTET STRING (CONTAINING T)
// is a plain octet string, and a bound above MaxInt64 is emitted with its literal text like free5gc/ngap.
func TestGenerateContainingAndUint64(t *testing.T) {
	out, err := generate(t, "A ::= INTEGER (0..18446744073709551615)\nB ::= OCTET STRING (CONTAINING A)\nC ::= INTEGER (0..10, ..., 20..30)")
	if err != nil {
		t.Fatal(err)
	}
	for _, w := range []string{
		"type A struct { Value int64 `aper:\"valueLB:0,valueUB:18446744073709551615\"` }",
		"type B struct { Value aper.OctetString }",
		"type C struct { Value int64 `aper:\"valueExt,valueLB:0,valueUB:10\"` }",
	} {
		if !strings.Contains(out, w) {
			t.Errorf("missing %q in output %s", w, out)
		}
	}
}
