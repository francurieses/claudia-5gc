const (
	syntheticDir = "testdata/synthetic"
	gentestDir   = "internal/gentest"
	gentestHdr   = "Code generated by tools/asn1gen from testdata/synthetic. DO NOT EDIT."
)

// TestSyntheticReproducible regenerates internal/gentest from the synthetic ASN.1 and fails
// when the committed files differ (run `go generate ./tools/asn1gen/...` to refresh).
func TestSyntheticReproducible(t *testing.T) {
	files, err := Generate(syntheticDir, gogen.Config{Package: "gentest", Header: gentestHdr, AperImport: "github.com/free5gc/aper"})
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 3 {
		t.Errorf("generated %d files, want 3 (two modules + containers)", len(files))
	}
	for name, want := range files {
		got, err := os.ReadFile(filepath.Join(gentestDir, name))
		if err != nil {
			t.Fatalf("committed %s: %v", name, err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s is stale: run `go generate ./tools/asn1gen/...`", name)
		}
	}
	// No committed generated file may be left over from a previous generator version.
	ents, err := filepath.Glob(filepath.Join(gentestDir, "*.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range ents {
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		if strings.HasPrefix(string(b), generatedMarker) {
			if _, ok := files[filepath.Base(p)]; !ok {
				t.Errorf("stale generated file %s", p)
			}
		}
	}
}

func TestRunCLI(t *testing.T) {
	out := t.TempDir()
	var so, se bytes.Buffer
	args := []string{"-in", syntheticDir, "-out", out, "-pkg", "x", "-header", "Code generated by tools/asn1gen cli test. DO NOT EDIT."}
	if rc := run(args, &so, &se); rc != 0 {
		t.Fatalf("rc=%d stderr=%s", rc, se.String())
	}
	if !strings.Contains(so.String(), "wrote 3 files") {
		t.Errorf("stdout = %q", so.String())
	}
	b, err := os.ReadFile(filepath.Join(out, "syn_msgs.go"))
	if err != nil || !strings.HasPrefix(string(b), "// Code generated by tools/asn1gen cli test. DO NOT EDIT.\n\npackage x\n") {
		t.Fatalf("output file: %v %.60s", err, b)
	}
	if _, err := format.Source(b); err != nil {
		t.Errorf("output is not gofmt-able: %v", err)
	}

	// A re-run removes stale generated files but keeps hand-written ones.
	stale := filepath.Join(out, "old.go")
	hand := filepath.Join(out, "hand.go")
	os.WriteFile(stale, []byte("// Code generated by tools/asn1gen old. DO NOT EDIT.\npackage x\n"), 0o644)
	os.WriteFile(hand, []byte("package x\n"), 0o644)
	if rc := run(args, &so, &se); rc != 0 {
		t.Fatalf("second run rc=%d: %s", rc, se.String())
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Error("stale generated file was not removed")
	}
	if _, err := os.Stat(hand); err != nil {
		t.Error("hand-written file was removed")
	}
}

func TestRunCLIErrors(t *testing.T) {
	bad := t.TempDir()
	os.WriteFile(filepath.Join(bad, "bad.asn"), []byte("M DEFINITIONS ::= BEGIN A ::= SEQUENCE { END"), 0o644)
	tests := []struct {
		name string
		args []string
		rc   int
		msg  string
	}{
		{"no flags", nil, 2, "-in and -out are required"},
		{"bad header", []string{"-in", "x", "-out", "y", "-header", "nope"}, 2, "must start with"},
		{"unknown flag", []string{"-bogus"}, 2, "flag provided but not defined"},
		{"no asn files", []string{"-in", t.TempDir(), "-out", t.TempDir()}, 1, "no *.asn files"},
		{"syntax error", []string{"-in", bad, "-out", t.TempDir()}, 1, "bad.asn"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			var so, se bytes.Buffer
			if rc := run(tc.args, &so, &se); rc != tc.rc || !strings.Contains(se.String(), tc.msg) {
				t.Errorf("rc=%d stderr=%q, want rc=%d containing %q", rc, se.String(), tc.rc, tc.msg)
			}
		})
	}
}

// TestSpecModulesGenerate generates from the extracted TS 38.413 modules (Rel-15 and
// Rel-19; git-ignored, skipped when absent) and checks that all six modules parse, that
// the output is gofmt-clean and that it type-checks (go vet in a scratch package inside
// the module so the aper import resolves).
func TestSpecModulesGenerate(t *testing.T) {
	for _, rel := range []string{"r15", "r19"} {
		t.Run(rel, func(t *testing.T) {
			dir := filepath.Join("../../specs/asn1/ngap", rel)
			if _, err := os.Stat(dir); err != nil {
				t.Skipf("%s not found (git-ignored, CI has no 3GPP text; run scripts/extract-asn1.sh). CI regression guard is step 4.3: committed generated output plus go generate reproducibility: %v", dir, err)
			}
			files, err := Generate(dir, gogen.Config{Package: "ngapType", Header: "Code generated by tools/asn1gen test. DO NOT EDIT.", AperImport: "github.com/free5gc/aper"})
			if err != nil {
				t.Fatal(err)
			}
			for _, m := range []string{"ngap_commondatatypes.go", "ngap_constants.go", "ngap_containers.go", "ngap_ies.go", "ngap_pdu_contents.go", "ngap_pdu_descriptions.go"} {
				if _, ok := files[m]; !ok && m != "ngap_containers.go" { // NGAP-Containers only holds parameterised types
					t.Errorf("no output for module file %s", m)
				}
			}
			if _, ok := files["protocol_containers.go"]; !ok {
				t.Error("no instantiated containers generated")
			}
			for n, b := range files {
				if f, err := format.Source(b); err != nil || !bytes.Equal(f, b) {
					t.Errorf("%s is not gofmt-clean (%v)", n, err)
				}
			}
			scratch, err := os.MkdirTemp(".", "_scratch")
			if err != nil {
				t.Fatal(err)
			}
			defer os.RemoveAll(scratch)
			for n, b := range files {
				if err := os.WriteFile(filepath.Join(scratch, n), b, 0o644); err != nil {
					t.Fatal(err)
				}
			}
			cmd := exec.Command("go", "vet", "./"+scratch)
			cmd.Env = append(os.Environ(), "GOWORK=off")
			if out, err := cmd.CombinedOutput(); err != nil {
				t.Fatalf("generated %s does not type-check: %v\n%.2000s", rel, err, out)
			}
		})
	}
}

// writeSyntheticZip builds a zip holding a minimal docx whose paragraphs are the given lines.
func writeSyntheticZip(t *testing.T, lines []string) string {
	t.Helper()
	var doc strings.Builder
	doc.WriteString(`<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>`)
	for _, l := range lines {
		doc.WriteString("<w:p><w:r><w:t>" + l + "</w:t></w:r></w:p>")
	}
	doc.WriteString("</w:body></w:document>")
	var docx bytes.Buffer
	dz := zip.NewWriter(&docx)
	w, err := dz.Create("word/document.xml")
	if err != nil {
		t.Fatal(err)
	}
	w.Write([]byte(doc.String()))
	dz.Close()
	zpath := filepath.Join(t.TempDir(), "syn.zip")
	f, err := os.Create(zpath)
	if err != nil {
		t.Fatal(err)
	}
	zw := zip.NewWriter(f)
	w, err = zw.Create("spec.docx")
	if err != nil {
		t.Fatal(err)
	}
	w.Write(docx.Bytes())
	zw.Close()
	f.Close()
	return zpath
}

// TestExtractScriptStrict checks scripts/extract-asn1.sh fails closed on malformed blocks
// and warns about modules outside the wanted set (synthetic, project-authored docx).
func TestExtractScriptStrict(t *testing.T) {
	if _, err := exec.LookPath("python3"); err != nil {
		t.Skip("python3 not available")
	}
	if _, err := exec.LookPath("unzip"); err != nil {
		t.Skip("unzip not available")
	}
	full := []string{}
	for _, m := range []string{"NGAP-PDU-Descriptions", "NGAP-PDU-Contents", "NGAP-IEs", "NGAP-CommonDataTypes", "NGAP-Constants", "NGAP-Containers"} {
		full = append(full, "-- ASN1START", m+" DEFINITIONS AUTOMATIC TAGS ::= BEGIN", "END", "-- ASN1STOP")
	}
	tests := []struct {
		name    string
		extra   []string
		wantErr string // empty: success
		wantOut string
	}{
		{"ok", nil, "", ""},
		{"start without stop", []string{"-- ASN1START", "X DEFINITIONS ::= BEGIN"}, "has no ASN1STOP", ""},
		{"nameless block", []string{"-- ASN1START", "-- only a comment", "-- ASN1STOP"}, "cannot determine the module name", ""},
		{"unexpected module", []string{"-- ASN1START", "Other-Mod DEFINITIONS AUTOMATIC TAGS ::= BEGIN", "END", "-- ASN1STOP"}, "", "Other-Mod"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			zpath := writeSyntheticZip(t, append(append([]string{}, full...), tc.extra...))
			out := t.TempDir()
			cmd := exec.Command("../../scripts/extract-asn1.sh", zpath, out)
			b, err := cmd.CombinedOutput()
			if tc.wantErr == "" {
				if err != nil {
					t.Fatalf("unexpected failure: %v\n%s", err, b)
				}
				if tc.wantOut != "" && (!strings.Contains(string(b), "warning: modules found outside") || !strings.Contains(string(b), tc.wantOut)) {
					t.Fatalf("missing warning %q:\n%s", tc.wantOut, b)
				}
				return
			}
			if err == nil || !strings.Contains(string(b), tc.wantErr) {
				t.Fatalf("want failure containing %q, got err=%v\n%s", tc.wantErr, err, b)
			}
		})
	}
}
